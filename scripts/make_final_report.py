"""Assemble docs/final_report.md from the generated report JSONs (no hand-typed metrics)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "reports"


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def lead_table(res: dict, models: list[str], cols: list[tuple[str, str]]) -> str:
    leads = list(next(iter(res.values()))["leads"])
    out = ["| model | " + " | ".join(f"{c[1]} {L}h" for c in cols for L in leads) + " |",
           "|---|" + "---|" * (len(cols) * len(leads))]
    for m in models:
        if m not in res:
            continue
        out.append(f"| {m} | " + " | ".join(str(res[m]["leads"][L].get(c[0], "–")) for c in cols for L in leads) + " |")
    return "\n".join(out)


def main() -> None:
    ev, sat, lf, loc, perf, dq = (load(n) for n in ("evaluation.json", "satellite_evaluation.json",
                                                    "landfall_evaluation.json", "localization.json",
                                                    "performance.json", "data_quality.json"))
    L = ["# Final project report: Tropicast v0.2", "",
         "> Generated by `scripts/make_final_report.py` from `reports/*.json`. Metrics are copied, never typed. "
         "Experimental research output; not an official forecast.", ""]
    L += ["## 1. Summary",
          "Tropicast is an open research platform for North Indian Ocean tropical cyclones. It ingests IBTrACS "
          "(RSMC New Delhi), SHIPS IO environmental predictors and HURSAT-B1 IR imagery. It trains leakage-safe "
          "track, intensity, rapid-intensification, satellite-intensity and centre-localisation models; calibrates "
          "their uncertainty; verifies them on unseen seasons; and serves everything through a FastAPI service and "
          "dashboard with full provenance.", ""]
    if dq:
        L += ["## 2. Data", f"- Data version `{dq['data_version']}`; {dq['storms']} storms in the domain; "
              f"QC dropped {dq['qc']['dropped']}.",
              f"- Environment: {dq.get('env_cases_matched')} SHIPS cases matched to {dq.get('env_storms')} storms.", ""]
    if sat:
        L += [f"- Imagery: {sat['data']['images']} labelled HURSAT images from {sat['data']['storms']} storms "
              f"({sat['data']['seasons'][0]}–{sat['data']['seasons'][1]}).", ""]
    if ev:
        sel = ev["selection"]
        main = [m for m in ev["results"]["test"] if "[" not in m]
        L += ["## 3. Track and intensity forecasts (test seasons "
              f"{ev['split']['test'][0]}–{ev['split']['test'][1]})",
              f"Selected on validation: track **{sel['track']}**, intensity **{sel['intensity']}**, RI **{sel['ri']}**.", "",
              "### Mean track error (km)", lead_table(ev["results"]["test"], main, [("track_err_mean_km", "")]), "",
              "### Track skill vs persistence (%)",
              lead_table(ev["results"]["test"], [m for m in main if m != "persistence"],
                         [("track_skill_vs_persistence_pct", "")]), "",
              "### Wind MAE (kt)", lead_table(ev["results"]["test"], main, [("wind_mae_kt", "")]), "",
              "### Calibration: empirical coverage of the 90 % track radius and the 90 % wind interval",
              lead_table(ev["results"]["test"], [sel["track"]], [("track_cov_90", "track"), ("wind_cov_90", "wind")]), "",
              "### Environment ablation (2019–2021 cases with SHIPS)",
              lead_table(ev["results"]["test_env"], ev["env_ablation_models"],
                         [("track_err_mean_km", "km"), ("wind_mae_kt", "kt")]), ""]
        ri = ev["rapid_intensification"]
        L += ["### Rapid intensification (experimental)", "| split | model | Brier | BSS | AUC | events |",
              "|---|---|---|---|---|---|"]
        for sp, d in ri.items():
            for k, r in d.items():
                L.append(f"| {sp} | {k} | {r['brier']} | {r['brier_skill']} | {r['roc_auc']} | {r['n_positive']}/{r['n']} |")
        L.append("")
    if sat:
        L += ["## 4. Satellite study (nested season-block CV)", "### Intensity estimation (kt), common subset",
              "| configuration | MAE | RMSE | bias |", "|---|---|---|---|"]
        for k, v in sat["estimation"]["common_subset"].items():
            L.append(f"| {k} | {v['mae']} | {v['rmse']} | {v['bias']} |")
        L += ["", "### 24 h intensity change (kt)", "| configuration | MAE | RMSE |", "|---|---|---|"]
        for k, v in sat["forecast_dw24"].items():
            L.append(f"| {k} | {v['mae']} | {v['rmse']} |")
        L += ["", "### Stage classification", "| model | accuracy | macro-F1 |", "|---|---|---|"]
        for k, v in sat["stage_classification"].items():
            L.append(f"| {k} | {v['accuracy']} | {v['macro_f1']} |")
        cov = [c["coverage"] for c in sat["cnn"]["interval90"]]
        L += ["", f"CNN 90 % interval coverage per fold: {cov}", ""]
    if loc:
        L += ["## 5. Centre localisation", "| method | mean km | median km | p90 km |", "|---|---|---|---|"]
        for k in ("cnn_heatmap", "baseline_coldest_cloud", "baseline_crop_centre"):
            v = loc[k]
            L.append(f"| {k} | {v['mean_km']} | {v['median_km']} | {v['p90_km']} |")
        L += ["", f"Test seasons {loc['test_seasons']}; reference = best-track centre (weak label).", ""]
    if lf:
        L += ["## 6. Landfall probability (72 h)",
              f"- {lf['n']} issues from {lf['test_storms']} test storms; {lf['n_positive']} landfalls.",
              f"- Brier {lf['brier']} vs climatology {lf['brier_climatology']} → BSS {lf['brier_skill']}; "
              f"AUC {lf['roc_auc']}.", "", "| forecast bin | n | mean forecast | observed |", "|---|---|---|---|"]
        for b in lf["reliability"]:
            L.append(f"| {b['bin']} | {b['n']} | {b['mean_forecast']} | {b['observed_freq']} |")
        L.append("")
    if perf:
        L += ["## 7. Performance (API, CPU, warm)", "| endpoint | p50 ms | p95 ms |", "|---|---|---|"]
        for k, v in perf.items():
            if not k.startswith("_"):
                L.append(f"| {k} | {v['p50_ms']} | {v['p95_ms']} |")
        L.append("")
    L += ["## 8. Objectives: status",
          "| # | objective | status |", "|---|---|---|",
          "| 1 | multi-source data intelligence | IBTrACS, SHIPS, HURSAT, Natural Earth implemented; ERA5, IMERG, MOSDAC blocked by credentials |",
          "| 2 | detection / centre / eye | centre localisation implemented; eye shown via IR eye-contrast + ARCHER; cyclone-vs-non-cyclone detection not feasible with storm-centred archive |",
          "| 3 | IMD classification | implemented (agency-safe); stage classification from imagery evaluated |",
          "| 4 | intensity estimation + uncertainty | satellite CNN + fusion, nested CV, conformal intervals |",
          "| 5 | track forecasting 6–72 h + uncertainty | implemented, calibrated, verified |",
          "| 6 | intensity forecast + RI | implemented; RI experimental with proper scores |",
          "| 7 | ocean/atmosphere | SHIPS shear, RH, SST, OHC, MPI, divergence, vorticity; ablation reported |",
          "| 8 | risk & uncertainty | landfall/strike probabilities verified; no wind-field/surge/rain (by design) |",
          "| 9 | explainable AI | Grad-CAM, modality ablations, IR structure features |",
          "| 10 | real-time monitoring | pipeline, freshness, notifications, audit; latency limited by IBTrACS |", "",
          "## 9. Limitations", "See docs/model_card.md. Main points: best-track label noise; HURSAT ends in 2015 and "
          "SHIPS in 2021, so live forecasts use track history only; IBTrACS latency is days; centre-based risk only.",
          "", "## 10. Future work", "See docs/roadmap.md."]
    (ROOT / "docs" / "final_report.md").write_text("\n".join(L) + "\n")
    print("wrote docs/final_report.md")


if __name__ == "__main__":
    main()
